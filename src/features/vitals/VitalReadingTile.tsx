import React from 'react';
import { Clock, Radio } from 'lucide-react';
import { Vital } from '../../types';
import { StatusBadge } from '../../components/ui';
import { evaluateReading, isSimulatedReading, isStale, ReadingStatus, vitalDefinition } from '../../constants/vitals';
import { formatDateTime, formatRelative } from '../../utils/format';

export const READING_BADGE: Record<ReadingStatus, { severity: 'success' | 'warning' | 'danger' | 'neutral'; label: string } | null> = {
  within: { severity: 'success', label: 'Within limits' },
  outside: { severity: 'warning', label: 'Outside limits' },
  critical: { severity: 'danger', label: 'Critical' },
  unknown: null
};

export const ReadingStatusBadge: React.FC<{ vital: Vital }> = ({ vital }) => {
  const badge = READING_BADGE[evaluateReading(vital)];
  if (!badge) return null;
  return <StatusBadge severity={badge.severity}>{badge.label}</StatusBadge>;
};

/** Freshness / provenance marker so stale or simulated readings are never mistaken for live clinical data. */
export const ReadingSource: React.FC<{ vital: Vital }> = ({ vital }) => {
  if (isSimulatedReading(vital)) {
    return (
      <span className="inline-flex items-center gap-1 text-2xs font-medium text-sky-700 dark:text-sky-300" title="Generated by the in-app simulated telemetry feed">
        <Radio className="h-3 w-3" aria-hidden />
        Simulated feed
      </span>
    );
  }
  if (isStale(vital)) {
    return (
      <span className="inline-flex items-center gap-1 text-2xs font-medium text-amber-700 dark:text-amber-300" title="Last reading is more than 24 hours old">
        <Clock className="h-3 w-3" aria-hidden />
        Stale
      </span>
    );
  }
  return null;
};

const VitalReadingTile: React.FC<{ vital: Vital; selected?: boolean; onClick?: () => void }> = ({ vital, selected, onClick }) => {
  const def = vitalDefinition(vital.type);
  const status = evaluateReading(vital);
  const accent =
    status === 'critical'
      ? 'border-l-red-500'
      : status === 'outside'
      ? 'border-l-amber-500'
      : 'border-l-transparent';

  const body = (
    <>
      <p className="truncate text-xs font-medium text-slate-500 dark:text-slate-400">{def?.label || vital.type}</p>
      <p className="mt-1 flex items-baseline gap-1">
        <span className="text-xl font-semibold tracking-tight tabular-nums text-slate-900 dark:text-slate-50">{vital.value}</span>
        <span className="text-xs font-medium text-slate-500">{vital.unit}</span>
      </p>
      <div className="mt-2 flex flex-wrap items-center justify-between gap-x-2 gap-y-1.5">
        <div className="flex min-w-0 flex-col">
          <time className="text-xs tabular-nums text-slate-500" dateTime={vital.recorded_at} title={formatDateTime(vital.recorded_at)}>
            {formatRelative(vital.recorded_at)}
          </time>
          <ReadingSource vital={vital} />
        </div>
        <ReadingStatusBadge vital={vital} />
      </div>
    </>
  );

  const base = `rounded-lg border border-l-[3px] bg-white p-3 text-left dark:bg-slate-900 ${accent} ${
    selected ? 'border-brand-500 ring-1 ring-brand-500 dark:border-brand-500' : 'border-slate-200 dark:border-slate-800'
  }`;

  if (onClick) {
    return (
      <button type="button" onClick={onClick} aria-pressed={selected} className={`${base} transition-colors hover:border-slate-300 dark:hover:border-slate-700`}>
        {body}
      </button>
    );
  }
  return <div className={base}>{body}</div>;
};

export default VitalReadingTile;
